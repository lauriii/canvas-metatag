<?php

/**
 * @file
 * Writes src/RegistryStrings.php from the two data files.
 *
 * Each string the dialog shows from data/schema-types.json and
 * data/search-features.json becomes a literal TranslatableMarkup, so that it
 * is extracted for translation. Run from the module root:
 * `php scripts/registry-strings.php`. CI fails when the committed file
 * differs from what this writes.
 */

declare(strict_types=1);

$root = dirname(__DIR__);
$read = static fn (string $name): array => json_decode((string) file_get_contents("$root/data/$name.json"), TRUE, 32, JSON_THROW_ON_ERROR);

$strings = [];
$add = static function (mixed $text) use (&$strings): void {
  if (is_string($text) && $text !== '') {
    $strings[$text] = TRUE;
  }
};
$registry = $read('schema-types');
// The parts of each shape: a venue's name, an address's country.
foreach ($registry['$shapes'] ?? [] as $shape) {
  foreach ($shape['parts'] as $part) {
    $add($part['label'] ?? NULL);
    array_map($add, array_values($part['option_labels'] ?? []));
  }
}
unset($registry['$shapes']);
foreach ($registry as $type) {
  $add($type['label'] ?? NULL);
  $add($type['variants'] ?? NULL);
  foreach (['label', 'name', 'earn', 'not_for'] as $key) {
    $add($type['kind'][$key] ?? NULL);
  }
  foreach ($type['props'] ?? [] as $prop) {
    $add($prop['label']);
    $add($prop['ref']['label'] ?? NULL);
    array_map($add, array_values($prop['option_labels'] ?? []));
  }
  foreach ($type['slots'] ?? [] as $slot) {
    $add($slot['label'] ?? NULL);
  }
  foreach ($type['say'] ?? [] as $sentence) {
    array_map($add, $sentence);
  }
}
$rules = $read('search-features');
foreach ($rules['facts'] as $fact) {
  $add($fact['label']);
  $add($fact['need']);
}
foreach ($rules['features'] as $feature) {
  foreach (['label', 'for', 'where'] as $key) {
    $add($feature[$key] ?? NULL);
  }
  array_map($add, $feature['confirm'] ?? []);
  foreach ($feature['rules'] ?? [] as $rule) {
    $add($rule['need'] ?? NULL);
  }
  $add($feature['elsewhere'] ?? NULL);
  foreach ($feature['not_for'] ?? [] as $not) {
    $add($not['reason']);
    $add($not['why']);
  }
}

$lines = '';
foreach (array_keys($strings) as $text) {
  $literal = var_export($text, TRUE);
  $lines .= "      $literal => new TranslatableMarkup($literal, [], ['context' => 'canvas_metatag:schema']),\n";
}

file_put_contents("$root/src/RegistryStrings.php", <<<PHP
<?php

declare(strict_types=1);

namespace Drupal\\canvas_metatag;

use Drupal\\Core\\StringTranslation\\TranslatableMarkup;

/**
 * The strings of the type registry and the search features rules.
 *
 * Generated by scripts/registry-strings.php from data/schema-types.json and
 * data/search-features.json; do not edit. Each string is a literal here, so
 * that it is extracted for translation.
 */
final class RegistryStrings {

  /**
   * Each string by its English text.
   *
   * @return array<string, \\Drupal\\Core\\StringTranslation\\TranslatableMarkup>
   *   English => the translatable string.
   */
  public static function all(): array {
    return [
$lines    ];
  }

}

PHP);
